// FUNCTION: DECKDLL 0x100100e6
// FUNCTION: MAGIC 0x004e0225
bool check_basic(csvid_t csvid)
{
  if (csvid == CARD_ID_SWAMP ||
      csvid == CARD_ID_ISLAND ||
      csvid == CARD_ID_FOREST ||
      csvid == CARD_ID_MOUNTAIN ||
      csvid == CARD_ID_PLAINS)
    return true;

  return false;
}
