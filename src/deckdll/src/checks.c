// FUNCTION: DECKDLL 0x1001013d
// FUNCTION: MAGIC 0x004e0291
bool check_restricted(csvid_t csvid)
{
  int i;

  for (i = 0; i < 35; ++i)
    if (restrictions[i].csvid == csvid && (restrictions[i].restriction & RST_RESTRICTED))
      return true;
  return false;
}

