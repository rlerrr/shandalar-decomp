#define IS_SICK(player_, card_) (((PLAYER_CARD_INSTANCE(player_, card_).state & STATE_SUMMONSICK_BOTH) != 0) && \
             ((global_cards_data[PLAYER_CARD_INSTANCE(player_, card_).internal_card_id].type & TYPE_CREATURE) != 0))

